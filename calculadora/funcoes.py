def soma(n1,n2):
    return n1+n2

def subtrcao(n1,n2):
    return n1-n2

def multiplicacao(n1,n2):
    return n1*n2

def divisao(n1,n2):
    if n2<=0:
        return "Erro: Nenhum número é divisivel por 0"
    return n1/n2

def potencia(n1,n2):
    return n1 ** n2

def raiz(n1,n2):
    return n1 ** (1/n2)